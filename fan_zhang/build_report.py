"""生成 Fan & Zhang (2020) 复现报告（离线 HTML）。数字从 output/ 读取。输出: report.html"""
import os
import sys

import polars as pl

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'harq'))
from build_report import CSS, table  # noqa: E402

OUT = os.path.join(HERE, 'report.html')
O = os.path.join(HERE, 'output')
ORDER = ['期限结构', '动量', '套保压力', '波动率', '持仓变化', '流动性', '偏度', '价值', '汇率', '通胀']
PER = ['2004-02~2017-05（论文样本期）', '2017-06~2026-08（样本外）', '全样本']
# 论文 Table 4（年化，t），m = 1..4
PAPER = {
    '期限结构': ['15.9（3.24）', '17.5（3.94）', '13.8（3.01）', '11.7（2.57）'], '套保压力': ['2.9（0.73）', '2.7（0.74）', '8.1（2.06）', '−0.8（−0.21）'],
    '动量': ['21.9（4.13）', '17.4（3.59）', '16.7（3.10）', '15.3（2.75）'], '波动率': ['10.5（2.43）', '6.9（1.59）', '4.9（1.07）', '4.8（1.02）'],
    '持仓变化': ['−3.7（−0.94）', '−5.6（−1.52）', '−3.1（−0.95）', '−5.5（−1.64）'], '流动性': ['−6.8（−1.43）', '2.9（0.60）', '0.9（0.22）', '−1.4（−0.42）'],
    '汇率': ['4.8（0.83）', '1.0（0.17）', '1.5（0.26）', '0.8（0.15）'], '通胀': ['2.2（0.44）', '−0.0（−0.01）', '4.8（1.00）', '2.0（0.41）'],
    '偏度': ['−9.6（−2.32）', '2.7（0.71）', '1.5（0.42）', '−1.0（−0.25）'], '价值': ['7.5（1.13）', '8.6（1.42）', '9.9（1.61）', '9.8（1.57）']}


def rd(n):
    return pl.read_parquet(os.path.join(O, f'{n}.parquet'))


def cell(r):
    if r is None or r['月数'] == 0 or r['年化%'] != r['年化%']:
        return '—'
    s = f"{r['年化%']:.1f}（{r['t']:.2f}）"
    return f'<b>{s}</b>' if abs(r['t']) >= 1.96 else s


def build():
    t4 = rd('table4')
    lo = rd('long_only')
    x = rd('panel')

    def get(setting, s, n, per):
        q = t4.filter(pl.col('设定').str.starts_with(setting) & (pl.col('策略') == s) & (pl.col('m') == n) & (pl.col('时期') == per))
        return q.row(0, named=True) if q.height else None

    mom1o = get('论文', '动量', 1, PER[1])
    ts2o = get('论文', '期限结构', 2, PER[1])
    val1o = get('论文', '价值', 1, PER[1])
    p = []
    p.append('<h1>中国商品期货风险溢价复现报告</h1><div class="meta">复现论文：John Hua Fan &amp; Tingxi Zhang，《The Untold Story of Commodity Futures in China》，'
             '<i>Journal of Futures Markets</i>，2020 · 中国商品期货第 1~4 近月合约，2005-01 至 2026-08（论文样本期 2004-02~2017-05，之后为样本外）</div>')
    p.append(f"<p class=\"lead\">论文的主要结论在中国、在论文之后的 9 年里<b>基本成立</b>：期限结构和动量是仅有的稳健溢价，"
             f"样本外依然显著（动量第 1 近月年化 {mom1o['年化%']:.1f}%，t = {mom1o['t']:.2f}；期限结构第 2 近月 {ts2o['年化%']:.1f}%，t = {ts2o['t']:.2f}）；"
             f"套保压力、持仓变化、流动性在两段都不显著；单纯做多没有溢价（论文样本期）。不同之处："
             f"波动率溢价在样本外反转；价值在样本外变成显著为负（第 1 近月 {val1o['年化%']:.1f}%，t = {val1o['t']:.2f}）；偏度在样本外转为正向。"
             f"另外，我们按论文定义构造的“套保压力”方向与论文相反；汇率不显著（同论文），通胀在论文样本期显著、样本外消失。</p>")
    p.append(f"<div class=\"kpis\"><div class=\"kpi\"><b>{mom1o['年化%']:.1f}%（t {mom1o['t']:.2f}）</b><span>动量，第 1 近月，2017 年后（样本外）</span></div>"
             f"<div class=\"kpi\"><b>{ts2o['年化%']:.1f}%（t {ts2o['t']:.2f}）</b><span>期限结构，第 2 近月，样本外</span></div>"
             f"<div class=\"kpi\"><b>{val1o['年化%']:.1f}%（t {val1o['t']:.2f}）</b><span>价值，第 1 近月，样本外（论文样本期不显著）</span></div>"
             f"<div class=\"kpi\"><b>{x.filter((pl.col('n') == 1) & (pl.col('m') < pl.date(2017, 5, 1))).group_by('m').len()['len'].median():.0f}</b><span>论文样本期每月品种数中位数（论文 30 个品种）</span></div></div>")

    p.append('<h2>论文讲了什么</h2>')
    p.append('<p>中国商品期货以散户为主、限仓严格、保证金随合约临近到期而提高，近月合约成交量不到全曲线的 10%。论文用 2004–2017 年 30 个品种，'
             '在第 1 到第 4 近月合约上分别检验了十种溢价，发现：单纯做多不赚钱；期限结构和动量溢价稳健（并被限仓和保证金“放大”）；'
             '套保压力、波动率、流动性、偏度溢价被制度“扭曲”；持仓变化、汇率、通胀溢价对制度环境敏感。</p>')
    p.append('<h2>复现对象与方法</h2>')
    p.append(table(['环节', '论文', '本次复现'], [
        ['合约', '近月持有到到期前一个月最后一个交易日再换月；第 m 近月同步换月', '同左（交割月 ≥ 当前月 + 2 的合约按到期排序取第 1~4 个）；官方结算价'],
        ['样本', '2004-02 ~ 2017-05，30 个品种（全样本有 ≥ 4 年数据、每月 ≥ 8 个品种）', '2005-01 ~ 2026-08；同样的筛选（一次性筛选，带前视，同论文）；论文样本期每月约 24 个品种；纤维板 2019-12 改报价单位，只用 2019-09 以前'],
        ['组合', '四分组，多头 − 空头（50% 保证金口径），等权，月度调仓', '同左'],
        ['信号', '附录 A：期限结构 ln F1 − ln F2、套保比率 |ΔOI|/成交量、过去 12 个月平均月对数收益、36 个月变异系数（方差/|均值|）、总持仓变化、Amivest（2 个月）、汇率与通胀 42 个月 beta、12 个月偏度、3.5~4.5 年前均价/现价',
         '同左。汇率：论文用 BIS 人民币有效汇率，这里用人民币对美元月升值（−Δln USDCNH，2012 年起，故论文样本期内只有 27 个月）；通胀：论文用“实际 − 预测”的意外通胀，这里用 CPI 同比的月度变化，beta 滞后一个月（CPI 次月公布）'],
        ['持仓门槛', '无', '同论文；另做“合约持仓 ≥ 100 手且有成交”的稳健性']]))

    p.append('<h2>一、单纯做多（对应论文 Table 3）</h2>')
    rows = [[r['m'], r['时期'], f"{r['年化%']:.2f}", f"{r['t']:.2f}", f"{r['年化波动%']:.1f}", f"{r['夏普']:.2f}"] for r in lo.iter_rows(named=True)]
    p.append(table(['第 m 近月', '时期', '年化%', 't', '年化波动%', '夏普'], rows))
    p.append('<p>论文样本期内单纯做多不赚钱，与论文一致；2017 年以后年化 6%~7%，接近显著，反映了 2020–2022 年的商品大牛市。</p>')

    p.append('<h2>二、十种多空策略（对应论文 Table 4）</h2>')
    p.append('<p>每格为年化收益%（Newey-West t），|t| ≥ 1.96 加粗。“论文”列是 Fan &amp; Zhang 的 Table 4。</p>')
    for n in (1, 2, 3, 4):
        rows = []
        for s in ORDER:
            rows.append([s, PAPER[s][n - 1]] + [cell(get('论文', s, n, per)) for per in PER])
        p.append(f'<h3>第 {n} 近月</h3>' + table(['策略', '论文（2004–2017）', '复现：论文样本期', '样本外 2017-06 ~ 2026-08', '全样本'], rows))

    p.append('<h3>稳健性：只保留当天持仓 ≥ 100 手且有成交的合约</h3>')
    rows = []
    for s in ORDER[:8]:
        rows.append([s] + [cell(get('稳健性', s, n, PER[2])) for n in (1, 2, 3, 4)])
    p.append(table(['策略（全样本）', '第 1 近月', '第 2 近月', '第 3 近月', '第 4 近月'], rows))

    p.append('<h2>与论文的比较</h2>')
    p.append('<ul><li><b>复现一致的</b>：单纯做多无溢价；动量在各期限都显著；期限结构在第 2~4 近月显著；持仓变化、流动性不显著；第 1 近月的波动率溢价显著为正、偏度为负。</li>'
             '<li><b>不一致的</b>：第 1 近月的期限结构比论文弱（6% 对 16%），第 2 近月反而很强（19%）。原因可能是我们第 1 近月的合约在中国常常不活跃，'
             '“近月 vs 次近月”价差噪声大；另外论文样本从 2004-02 开始、我们从 2005-01 开始。'
             '套保压力（|ΔOI|/成交量）在各期限都为负，论文在第 3 近月为显著正值（8.1%）。论文自己也承认这只是很粗糙的代理变量。</li>'
             '<li>汇率各期限都不显著，与论文一致（但我们的汇率数据只覆盖论文样本期的最后 27 个月）。通胀在第 1 近月显著为正（10.5%，t 2.35），强于论文（2.2%），'
             '可能与我们用的简化通胀代理有关；样本外消失。</li></ul>')
    p.append('<h2>论文之后的 9 年（样本外）</h2>')
    p.append('<ul><li><b>动量、期限结构依然成立</b>：动量在第 1、2 近月更强，期限结构在第 2 近月依然显著。这与本库其他复现的发现一致：中国商品的稳健溢价就是 carry 和动量。</li>'
             '<li><b>波动率溢价反转</b>：论文样本期第 1 近月显著为正，之后为负。论文认为它来自近月的限仓，这个解释在样本外站不住。</li>'
             '<li><b>价值显著为负</b>：2017 年后长期跌得多的品种继续跌（第 1 近月 t ≈ −3.2），与本库 AMP 复现中“中国商品价值因子为负”一致。</li>'
             '<li><b>偏度转为正向</b>：第 3、4 近月做多左偏、做空右偏在样本外赚钱（t ≈ 2），与本库偏度复现中“2016 年后偏度溢价转正”一致。</li></ul>')
    p.append('<h2>代码与数据</h2>')
    p.append(table(['文件', '作用'], [['fz.py', '构造第 1~4 近月面板、十种信号与四分组多空组合'], ['build_report.py', '生成本报告'],
                                    ['../basis_momentum/data.py', '第 m 近月合约选择、月末曲线、持有月内逐日数据（共用）']]))
    html = ('<!doctype html><html lang="zh"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">'
            f'<title>中国商品风险溢价</title><style>{CSS}</style></head><body><main>{"".join(p)}</main></body></html>')
    with open(OUT, 'w', encoding='utf-8') as fh:
        fh.write(html)
    print('wrote', OUT)


if __name__ == '__main__':
    build()
